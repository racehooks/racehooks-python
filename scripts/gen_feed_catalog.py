#!/usr/bin/env python3
"""Generate racehooks/models/_feed_catalog.py from catalog/feed-catalog.json.

The JSON is the vendored copy of the RaceHooks feed catalog (schema
``racehooks.feed-catalog/1``). Usage: ``python scripts/gen_feed_catalog.py``.
"""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "catalog" / "feed-catalog.json"
OUT = ROOT / "racehooks" / "models" / "_feed_catalog.py"


def literal(name: str, values: list) -> str:
    body = ",\n".join(f"    {json.dumps(v)}" for v in values)
    return f"{name} = Literal[\n{body},\n]\n"


def main() -> None:
    cat = json.loads(SRC.read_text(encoding="utf-8"))
    if cat["schema"] != "racehooks.feed-catalog/1":
        raise SystemExit(f"unsupported catalog schema: {cat['schema']}")
    # Same canonicalisation as the monorepo generator (JS JSON.stringify: no spaces, raw unicode).
    canon = json.dumps(
        {"families": cat["families"], "feeds": cat["feeds"]},
        separators=(",", ":"),
        ensure_ascii=False,
    )
    digest = hashlib.sha256(canon.encode("utf-8")).hexdigest()
    if digest != cat["contentHash"]:
        raise SystemExit(
            f"{SRC} is corrupt or hand-edited: contentHash {cat['contentHash']} != computed {digest}"
        )

    feeds = cat["feeds"]
    tiers = list(dict.fromkeys(f["tier"] for f in feeds))
    families = [f["category"] for f in cat["families"]]
    rows = "\n".join(
        "    FeedCatalogEntry("
        f"id={json.dumps(f['feedId'])}, name={json.dumps(f['name'], ensure_ascii=False)}, "
        f"family={json.dumps(f['family'])}, tier={json.dumps(f['tier'])}, "
        f"description={json.dumps(f['shortDesc'], ensure_ascii=False)}, "
        f"cadence={f.get('cadence')!r}),"
        for f in feeds
    )
    out = (
        '"""GENERATED by scripts/gen_feed_catalog.py from catalog/feed-catalog.json. Do not edit."""\n\n'
        "from __future__ import annotations\n\n"
        "from typing import Literal, NamedTuple, Optional, Tuple\n\n"
        "# Feed availability tier as published in the feed catalog. Not the account plan.\n"
        + literal("FeedAvailability", tiers)
        + "\n# Feed family (catalog category).\n"
        + literal("FeedFamily", families)
        + "\n# Canonical feed ids (the `feed` discriminator on every delivery).\n"
        + literal("FeedId", [f["feedId"] for f in feeds])
        + "\n\nclass FeedCatalogEntry(NamedTuple):\n"
        "    id: str\n    name: str\n    family: str\n    tier: str\n    description: str\n"
        "    cadence: Optional[str]\n\n\n"
        f'FEED_CATALOG_HASH = "{cat["contentHash"]}"\n\n'
        "FEED_CATALOG: Tuple[FeedCatalogEntry, ...] = (\n" + rows + "\n)\n"
    )
    OUT.write_text(out, encoding="utf-8")
    print(
        f"wrote {OUT.relative_to(ROOT)} ({len(feeds)} feeds, hash {cat['contentHash'][:12]})"
    )


if __name__ == "__main__":
    main()
